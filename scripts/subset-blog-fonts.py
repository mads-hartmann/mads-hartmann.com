#!/usr/bin/env python3
"""Regenerate the checked-in Muli WOFF2 files; not needed for site builds.

Requires fonttools==4.61.1 and brotli==1.2.0. See the blog README.
"""

from hashlib import sha256
from io import BytesIO
from pathlib import Path
from urllib.request import urlopen

from fontTools import subset
from fontTools.ttLib import TTFont


ROOT = Path(__file__).resolve().parents[1]
DESTINATION = ROOT / "sites/blog.mads-hartmann.com/src/fonts"
# The last Google Fonts revision containing Muli, before its Mulish redesign.
SOURCE = "https://raw.githubusercontent.com/google/fonts/1afe12072a7fff0c8eaacb36fa4c8c722192d5e7/ofl/muli/"
SOURCES = {
    "normal": ("Muli%5Bwght%5D.ttf", "764b12af6ea23ed1fac3cb9e34d30f648a426e6255a9b254f45da4e95dfe901b"),
    "italic": ("Muli-Italic%5Bwght%5D.ttf", "d8d4624d0b54f1af859f1f65552ca9d3c85d10122fc599b6331fc8a9b651a1a7"),
}
# Western Latin, Danish, combining accents, punctuation, and common symbols.
# Keep a reusable alphabet rather than a fragile list of today's article text.
UNICODES = (
    "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,"
    "U+0300-036F,U+2000-206F,U+2074,U+20AC,U+2122,U+2190-2199,"
    "U+2212,U+2215,U+2264-2265,U+FEFF,U+FFFD"
)


def download(filename, digest):
    with urlopen(SOURCE + filename, timeout=60) as response:
        data = response.read()
    if sha256(data).hexdigest() != digest:
        raise ValueError(f"Unexpected source checksum: {filename}")
    return data


def main():
    DESTINATION.mkdir(parents=True, exist_ok=True)
    license_text = download("OFL.txt", "7f55affd2bce8ed9be13297ba8df1a4a7e9835c2a006126dc2a1eb4ce75a7943")
    (DESTINATION / "OFL.txt").write_bytes(license_text)
    declarations = ["// Generated by scripts/subset-blog-fonts.py.\n"]
    for style, (filename, digest) in SOURCES.items():
        source = download(filename, digest)
        font = TTFont(BytesIO(source), recalcTimestamp=False)
        options = subset.Options()
        options.hinting = False
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=subset.parse_unicodes(UNICODES))
        subsetter.subset(font)
        # Keep the original variation axis: trimming it slightly rounds the
        # intermediate bold metrics. CSS below exposes only the original faces.
        font.flavor = "woff2"
        name = f"muli-latin-{style}.woff2"
        font.save(DESTINATION / name)
        print(f"{name}: {(DESTINATION / name).stat().st_size:,} bytes")
        # Share one download across the original three weight declarations.
        # Keeping discrete faces preserves CSS matching: h2's weight 300 still
        # selects 200, just as it did with the old Google Fonts stylesheet.
        for weight in (200, 400, 700):
            declarations.append(
                "@font-face {\n"
                '  font-family: "Muli";\n'
                f"  font-style: {style};\n"
                f"  font-weight: {weight};\n"
                "  font-display: swap;\n"
                f'  src: url("/fonts/{name}") format("woff2");\n'
                f"  unicode-range: {UNICODES};\n"
                "}\n"
            )
    (DESTINATION.parent / "_sass/fonts.scss").write_text("\n".join(declarations))


if __name__ == "__main__":
    main()
